def _session_key() -> str:
    import os
    custom = os.environ.get("YUER_SAOHUA_SESSION")
    if custom:
        return f"/tmp/yuer_saohua_used_{custom}.json"
    return f"/tmp/yuer_saohua_used_pp{os.getppid()}.json"

def _load_used() -> set:
    import os
    path = _session_key()
    if os.path.exists(path):
        try:
            with open(path) as f:
                return set(json.load(f))
        except Exception:
            return set()
    return set()

def _save_used(used: set):
    import os
    path = _session_key()
    try:
        with open(path, "w") as f:
            json.dump(sorted(used), f)
    except Exception:
        pass


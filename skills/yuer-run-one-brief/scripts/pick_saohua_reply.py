def _load_long_pool() -> list:
    """加载长版骚话池（410 条）= 主人 09-28 钦定·灵魂级·整改 v3.0。

    合并 V2（50 条硬核高潮版）+ V6（360 条第一人称沉浸版）= 长版池
      - V6 360 条 = 主人 09-27 钦定方向（默认主用）
      - V2 50 条 = 兜底补充（V6 文件读不到时 fallback）
    """
    # 1. V6 池优先加载
    try:
        import importlib.util
        import os as _os
        pool = []
        base = '~/.hermes/skills/creative/yuer-text-climax/scripts'
        for batch in range(1, 7):
            p = _os.path.join(base, f'saohua_v6_batch{batch}.py')
            if not _os.path.exists(p):
                continue
            spec = importlib.util.spec_from_file_location(f'saohua_v6_batch{batch}', p)
            m = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(m)
            pool.extend(getattr(m, f'SAOHUA_V6_BATCH{batch}', []))
        if pool:
            # V6 加载成功 = 主池
            pool.extend(SAOHUA_V2_POOL)  # V2 50 条兜底
            return pool
    except Exception:
        pass
    # 2. fallback = V2 池
    return list(SAOHUA_V2_POOL)



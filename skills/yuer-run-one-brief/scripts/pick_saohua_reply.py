def _score_against_tags(text: str, tags: list) -> int:
    """池句命中 brief 标签关键词的次数 = 匹配分"""
    score = 0
    for kw in tags:
        if kw in text:
            score += 1
    return score


def pick_matching(brief_text: str, top: int = 6, short: bool = True) -> list:
    """🔴 10-31 新增 = 按 brief 语义挑 = 池子当素材库不当正文

    用法：pick_saohua_reply.py --match "<brief 里的场景词，如：跪在地板上含住>" --top 6
    返回 = 匹配分最高的 N 条（并列随机打散）= 语儿照 brief 挑一条直接用 / 都不对就自己写

    判据 = 这条池句的场景 = brief 的场景 = 对得上 = 才能发
    """
    pool = SAOHUA_SHORT_POOL if short else _load_long_pool()
    used = _load_used()

    # brief 里出现过的标签 = 这次要的场景
    wanted = []
    for tag, kws in _SCENE_TAGS.items():
        if any(k in brief_text for k in kws):
            wanted.append(tag)

    scored = []
    for s in pool:
        if s in used:
            continue
        sc = 0
        for tag in wanted:
            sc += _score_against_tags(s, _SCENE_TAGS[tag]) * 2
        if sc > 0:
            scored.append((sc, s))

    scored.sort(key=lambda x: -x[0])
    top_items = scored[:top]
    if not top_items:
        return []
    # 同分的随机打散（避免永远第一条）
    best = top_items[0][0]
    same = [s for sc, s in scored if sc == best]
    others = [s for sc, s in scored if sc != best][:max(0, top - len(same))]
    return same[:top] + others


def mark_used(reply: str) -> None:
    """标记某条池句已用 = 防止同一会话重复"""
    used = _load_used()
    used.add(reply)
    _save_used(used)


